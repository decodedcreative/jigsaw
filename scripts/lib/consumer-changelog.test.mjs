import assert from "node:assert/strict";
import { describe, it } from "node:test";
import {
  checkPullRequestBody,
  extractConsumerChangelog,
  formatChangelogSummary,
  isBreaking,
  pullRequestNumbersFromSubjects,
} from "./consumer-changelog.mjs";
import { readFileSync } from "node:fs";

describe("extractConsumerChangelog", () => {
  it("reads bullets up to the next heading", () => {
    const body = [
      "## Changes",
      "- internal stuff",
      "",
      "## Consumer changelog",
      '- `SearchField` is named "Search" when it has no label.',
      "- **Breaking:** the design system now requires React 19.",
      "",
      "## Testing",
      "- 700 tests",
    ].join("\n");
    assert.deepEqual(extractConsumerChangelog(body), {
      found: true,
      none: false,
      entries: [
        '`SearchField` is named "Search" when it has no label.',
        "**Breaking:** the design system now requires React 19.",
      ],
    });
  });

  it("treats paragraphs as entries when there are no bullets, joining wrapped lines", () => {
    const body =
      "## Consumer changelog\nDefault theme colours are darker\nfor contrast.\n\nForm.Group accepts titleAs.\n";
    assert.deepEqual(extractConsumerChangelog(body).entries, [
      "Default theme colours are darker for contrast.",
      "Form.Group accepts titleAs.",
    ]);
  });

  it("recognises an explicit None, with or without a reason", () => {
    for (const text of [
      "None.",
      "None",
      "none — test-only change",
      "None. Test-only change.",
      "None: docs only",
      "N/A",
      "No consumer-facing changes.",
    ]) {
      assert.deepEqual(
        extractConsumerChangelog(`## Consumer changelog\n${text}\n`),
        { found: true, none: true, entries: [] },
        text,
      );
    }
  });

  it("treats the untouched PR template as an empty section", () => {
    const template = readFileSync(
      new URL("../../.github/pull_request_template.md", import.meta.url),
      "utf8",
    );
    assert.deepEqual(extractConsumerChangelog(template), {
      found: true,
      none: false,
      entries: [],
    });
  });

  it("doesn't mistake an entry that starts with the word None for an explicit None", () => {
    assert.deepEqual(
      extractConsumerChangelog(
        "## Consumer changelog\nNone of the APIs changed, but Select is faster.\n",
      ).entries,
      ["None of the APIs changed, but Select is faster."],
    );
  });

  it("stops at a horizontal rule or generated footer, and skips link definitions (real PR shapes)", () => {
    const body = [
      "## Consumer changelog",
      "Default theme colours are darker so they meet WCAG AA contrast.",
      "",
      "🤖 Generated with [Claude Code](https://claude.com/claude-code)",
      "",
      "https://claude.ai/code/session_x",
      "",
      "[JSW-124]: https://decodedcreative.atlassian.net/browse/JSW-124?atlOrigin=abc",
    ].join("\n");
    assert.deepEqual(extractConsumerChangelog(body).entries, [
      "Default theme colours are darker so they meet WCAG AA contrast.",
    ]);
    const withRule =
      "## Consumer changelog\nNone. No published package changes.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n\n[JSW-136]: https://x.example/JSW-136";
    assert.deepEqual(extractConsumerChangelog(withRule), {
      found: true,
      none: true,
      entries: [],
    });
    const linkOnly =
      "## Consumer changelog\n- Adds Tabs.\n[JSW-1]: https://x.example/JSW-1\n";
    assert.deepEqual(extractConsumerChangelog(linkOnly).entries, [
      "Adds Tabs.",
    ]);
  });

  it("reports a missing section", () => {
    assert.equal(extractConsumerChangelog("## Changes\n- stuff").found, false);
    assert.equal(extractConsumerChangelog(undefined).found, false);
  });

  it("accepts a level-3 heading and CRLF line endings", () => {
    assert.deepEqual(
      extractConsumerChangelog("### Consumer changelog\r\n- Adds Tabs.\r\n")
        .entries,
      ["Adds Tabs."],
    );
  });
});

describe("isBreaking / formatChangelogSummary", () => {
  it("detects the breaking marker in its usual spellings", () => {
    assert.equal(isBreaking("**Breaking:** React 19 only"), true);
    assert.equal(isBreaking("**Breaking**: React 19 only"), true);
    assert.equal(isBreaking("Breaking: React 19 only"), true);
    assert.equal(isBreaking("Fixes a breaking bug"), false);
  });

  it("puts breaking changes first, normalises the marker, adds PR numbers and drops duplicates", () => {
    assert.deepEqual(
      formatChangelogSummary([
        { pr: 101, entry: "Adds Tabs." },
        { pr: 103, entry: "Breaking: requires React 19." },
        { pr: 104, entry: "Adds Tabs." },
      ]),
      ["- **Breaking:** requires React 19. (#103)", "- Adds Tabs. (#101)"],
    );
  });
});

describe("pullRequestNumbersFromSubjects", () => {
  it("finds merge-commit and squash PR numbers, sorted and unique", () => {
    assert.deepEqual(
      pullRequestNumbersFromSubjects([
        "Merge pull request #99 from decodedcreative/feat/jsw-124",
        "JSW-136: Run ESLint in CI (#98)",
        "Merge pull request #98 from decodedcreative/feat/jsw-136",
        "fix typo",
      ]),
      [98, 99],
    );
  });
});

describe("checkPullRequestBody", () => {
  it("passes when no publishable package changed", () => {
    assert.equal(
      checkPullRequestBody({ body: "", touchesPublishablePackage: false }).ok,
      true,
    );
  });

  it("fails when the section is missing or empty, and passes with entries or None", () => {
    assert.equal(
      checkPullRequestBody({
        body: "## Changes",
        touchesPublishablePackage: true,
      }).ok,
      false,
    );
    assert.equal(
      checkPullRequestBody({
        body: "## Consumer changelog\n",
        touchesPublishablePackage: true,
      }).ok,
      false,
    );
    assert.equal(
      checkPullRequestBody({
        body: "## Consumer changelog\n- Adds Tabs.",
        touchesPublishablePackage: true,
      }).ok,
      true,
    );
    assert.equal(
      checkPullRequestBody({
        body: "## Consumer changelog\nNone.",
        touchesPublishablePackage: true,
      }).ok,
      true,
    );
  });
});
